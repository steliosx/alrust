#!/usr/bin/env python3
"""Write crates/alrust-domain/src/pytext.rs from the pinned interpreter.

The tables are the Python 3.12 text rules the Prometheus mapping needs
(SF-WEBHOOKS): str.isprintable() for repr(), and for int() the
characters it strips around a number and the Unicode decimal digits
(category Nd) it reads. Run with the pinned
CPython 3.12.14 (Unicode 15.0.0):

    python3.12 -I scripts/gen-pytext.py > crates/alrust-domain/src/pytext.rs
"""

import sys
import unicodedata

if sys.version_info[:2] != (3, 12) or unicodedata.unidata_version != '15.0.0':
    sys.exit(f'need CPython 3.12 with Unicode 15.0.0, not {sys.version.split()[0]} '
             f'/ {unicodedata.unidata_version}')


def hx(c):
    # Clippy's unreadable_literal: group hex digits in fours above 0xFFFF.
    return f'0x{c >> 16:X}_{c & 0xFFFF:04X}' if c > 0xFFFF else f'0x{c:04X}'


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        hit = pred(c) and not 0xD800 <= c <= 0xDFFF
        if hit and start is None:
            start = c
        if not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


non_printable = ranges(lambda c: not chr(c).isprintable())


def int_strips(c):
    # int() keeps ASCII as is and strips only C isspace() there; above
    # ASCII it strips str.isspace(). Probe int() itself.
    if 0xD800 <= c <= 0xDFFF:
        return False
    try:
        return int(chr(c) + '1' + chr(c)) == 1
    except ValueError:
        return False


spaces = [c for c in range(0x110000) if int_strips(c)]
zeros = [c for c in range(0x110000)
         if unicodedata.category(chr(c)) == 'Nd' and unicodedata.digit(chr(c)) == 0]
assert all(unicodedata.category(chr(z + i)) == 'Nd' and unicodedata.digit(chr(z + i)) == i
           for z in zeros for i in range(10))
assert len([c for c in range(0x110000) if unicodedata.category(chr(c)) == 'Nd']) == 10 * len(zeros)

w = sys.stdout.write
w(f"""//! Python {sys.version.split()[0]} text rules (Unicode {unicodedata.unidata_version}),
//! generated by `scripts/gen-pytext.py`; do not edit by hand.
//!
//! - [`is_printable`]: `str.isprintable()`, which `repr()` uses to decide
//!   which characters to escape ({len(non_printable)} ranges).
//! - [`is_int_space`]: the characters `int()` strips around a number
//!   ({len(spaces)}; not U+001C to U+001F, which `str.isspace()` accepts).
//! - [`decimal`]: the value of a Unicode decimal digit (category Nd), which
//!   `int()` accepts ({len(zeros)} runs of ten).

/// Inclusive ranges of the characters for which `str.isprintable()` is false.
#[rustfmt::skip]
const NON_PRINTABLE: &[(u32, u32)] = &[
""")
for a, b in non_printable:
    w(f'    ({hx(a)}, {hx(b)}),\n')
w("""];

/// The characters `int()` strips around a number.
#[rustfmt::skip]
const SPACES: &[u32] = &[
""")
for c in spaces:
    w(f'    {hx(c)},\n')
w("""];

/// The digit zero of each run of ten Unicode decimal digits.
#[rustfmt::skip]
const DECIMAL_ZEROS: &[u32] = &[
""")
for c in zeros:
    w(f'    {hx(c)},\n')
w("""];

/// Python `c.isprintable()`.
pub(crate) fn is_printable(c: char) -> bool {
    let c = u32::from(c);
    NON_PRINTABLE
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_err()
}

/// Whether `int()` strips `c` around a number.
pub(crate) fn is_int_space(c: char) -> bool {
    SPACES.binary_search(&u32::from(c)).is_ok()
}

/// The value of `c` as a Unicode decimal digit, as Python `int()` reads it.
pub(crate) fn decimal(c: char) -> Option<u32> {
    let c = u32::from(c);
    let i = DECIMAL_ZEROS.partition_point(|&z| z <= c).checked_sub(1)?;
    let d = c - DECIMAL_ZEROS.get(i)?;
    (d < 10).then_some(d)
}
""")
